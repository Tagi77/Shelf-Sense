export function createDemo(today = dayKey()): Product[] {
  const active = entries.map(
    ([
      key,
      name,
      nameEn,
      category,
      zone,
      temperature,
      days,
      amount,
      unit,
      price,
      photo,
    ]) => ({
      id: `demo-${key}`,
      name,
      nameEn,
      category,
      zone,
      temperature,
      expiresOn: addDays(days, today),
      addedOn: category === "protein" ? today : addDays(-2, today),
      amount,
      unit,
      price,
      photo,
      visual: "photo" as const,
      notes: "",
      state: "active" as const,
      archivedOn: null,
      demo: true,
    }),
  );
  return [
    ...active,
    ...[
      { ...active[5], id: "demo-eaten-tomato", amount: 600, price: 1080 },
      { ...active[6], id: "demo-eaten-bread", amount: 400, price: 750 },
      { ...active[4], id: "demo-eaten-milk", amount: 1, price: 650 },
    ].map((p) => ({
      ...p,
      state: "eaten" as const,
      archivedOn: addDays(-1, today),
    })),
  ];
}
export function mergeDemo(current: Product[], today = dayKey()) {
  const ids = new Set(current.map((p) => p.id));
  return [...current, ...createDemo(today).filter((p) => !ids.has(p.id))];
}
